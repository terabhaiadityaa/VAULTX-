-- 1. Table: users
CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    pin_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE public.users IS 'Cardholder identity and PBKDF2-HMAC-SHA256 salted PIN credentials.';
COMMENT ON COLUMN public.users.pin_hash IS 'Format: pbkdf2_sha256$<iterations>$<saltHex>$<hashHex>';

-- 2. Table: accounts (integer paise balance precision)
CREATE TABLE public.accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_number VARCHAR(32) NOT NULL UNIQUE,
    balance_paise BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_accounts_user
        FOREIGN KEY (user_id)
        REFERENCES public.users (id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_accounts_balance_non_negative
        CHECK (balance_paise >= 0),

    CONSTRAINT chk_accounts_status_valid
        CHECK (status IN ('active', 'blocked', 'closed'))
);

COMMENT ON TABLE public.accounts IS 'Bank accounts linked to users with balances in 64-bit integer paise.';
COMMENT ON COLUMN public.accounts.balance_paise IS '100 paise = 1 INR; prevents IEEE-754 floating-point rounding discrepancies.';

-- 3. Table: transactions (double-entry immutable ledger)
CREATE TABLE public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    transaction_type VARCHAR(16) NOT NULL,
    amount_paise BIGINT NOT NULL,
    related_account_id BIGINT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_transactions_account
        FOREIGN KEY (account_id)
        REFERENCES public.accounts (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_transactions_related_account
        FOREIGN KEY (related_account_id)
        REFERENCES public.accounts (id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_transactions_amount_positive
        CHECK (amount_paise > 0),

    CONSTRAINT chk_transactions_type_valid
        CHECK (transaction_type IN ('deposit', 'withdrawal', 'transfer_in', 'transfer_out'))
);

COMMENT ON TABLE public.transactions IS 'Immutable ledger. P2P transfers record linked transfer_out and transfer_in rows.';

-- 4. Table: login_attempts (brute-force rate limiting & 15-min lockout)
CREATE TABLE public.login_attempts (
    email TEXT PRIMARY KEY,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE public.login_attempts IS 'Tracks consecutive failed PIN entries and epoch lockout timestamps.';

-- 5. Performance Indexes
CREATE INDEX idx_accounts_user_id ON public.accounts (user_id);
CREATE INDEX idx_accounts_account_number ON public.accounts (account_number);
CREATE INDEX idx_transactions_account_id ON public.transactions (account_id);
CREATE INDEX idx_transactions_created_at ON public.transactions (created_at DESC);
CREATE INDEX idx_transactions_related_account_id ON public.transactions (related_account_id);

-- 6. Supabase Data API (PostgREST) Lockdown
-- Enable RLS with no permissive policies and revoke anon/authenticated access so
-- pin_hash and account balances are never exposed over the public Supabase REST API.
-- The Render C++ backend connects via the privileged postgres role.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.login_attempts ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.users, public.accounts, public.transactions, public.login_attempts
FROM anon, authenticated;
