// Generates a cryptographically random 12-digit simulated ATM card / account number.
std::string AuthService::generateAccountNumber() {
    unsigned char randomBytes[12];
    if (RAND_bytes(randomBytes, sizeof(randomBytes)) != 1) {
        return "";
    }

    // First digit is 1-9 to avoid leading zero
    std::string accountNumber;
    accountNumber += std::to_string(1 + (randomBytes[0] % 9));

    // Next 11 digits are 0-9
    for (int i = 1; i < 12; i++) {
        accountNumber += std::to_string(randomBytes[i] % 10);
    }

    return accountNumber;
}

// Issues a new simulated ATM Debit Card bound to a canonical E.164 mobile number
AuthResult AuthService::registerUser(
    const std::string& fullName,
    const std::string& countryCode,
    const std::string& mobileNumber,
    const std::string& email,
    const std::string& pin,
    const std::string& confirmPin,
    bool enforceConfirmPin
) {
    std::string cleanName = trimCopy(fullName);
    if (cleanName.length() < 2 || cleanName.length() > 100) {
        return {false, true, "Name must contain 2 to 100 characters.", -1, "", ""};
    }

    const PhoneParseResult parsedPhone = PhoneUtils::normalize(countryCode, mobileNumber);
    if (!parsedPhone.valid) {
        return {false, true, parsedPhone.errorMessage, -1, "", ""};
    }

    std::string cleanEmail = trimCopy(email);
    std::transform(cleanEmail.begin(), cleanEmail.end(), cleanEmail.begin(), [](unsigned char ch) {
        return static_cast<char>(std::tolower(ch));
    });

    const bool autoGeneratedEmail = cleanEmail.empty();
    auto generateSimEmail = []() {
        unsigned char randBuf[4];
        unsigned int suffix = 0;
        if (RAND_bytes(randBuf, sizeof(randBuf)) == 1) {
            suffix = (static_cast<unsigned int>(randBuf[0]) << 24)
                   | (static_cast<unsigned int>(randBuf[1]) << 16)
                   | (static_cast<unsigned int>(randBuf[2]) << 8)
                   | static_cast<unsigned int>(randBuf[3]);
        } else {
            suffix = static_cast<unsigned int>(std::rand());
        }
        return "mob_" + std::to_string(std::time(nullptr)) + "_" + std::to_string(suffix) + "@vaultx.sim";
    };

    if (autoGeneratedEmail) {
        cleanEmail = generateSimEmail();
    } else {
        size_t atPos = cleanEmail.find('@');
        if (atPos == std::string::npos || atPos == 0 ||
            cleanEmail.find('@', atPos + 1) != std::string::npos ||
            cleanEmail.find('.', atPos) == std::string::npos) {
            return {false, true, "Please enter a valid email address.", -1, "", ""};
        }
    }

    if (enforceConfirmPin && pin != confirmPin) {
        return {false, true, "PIN and Confirm PIN must match.", -1, "", ""};
    }

    // Hash the 6-digit PIN securely before storing
    std::string hashedPin = PinHasher::hashPin(pin);
    if (hashedPin.empty()) {
        return {false, true, "PIN must contain exactly 6 digits.", -1, "", ""};
    }

    for (int attempt = 0; attempt < 5; attempt++) {
        std::string accountNumber = generateAccountNumber();
        if (accountNumber.empty()) {
            return {false, false, "Account number generation failed.", -1, "", ""};
        }

        const RegistrationResult regRes = database.createCardAccount(
            cleanName,
            cleanEmail,
            parsedPhone.e164,
            hashedPin,
            accountNumber,
            1000000, // ₹10,000 promotional balance (1,000,000 paise)
            "Welcome simulation balance"
        );

        if (regRes.success) {
            return {true, false, regRes.message, regRes.userId, accountNumber, parsedPhone.e164};
        }
        if (regRes.duplicateMobile) {
            return {false, true, regRes.message, -1, "", ""};
        }
        if (regRes.duplicateAccount) {
            continue;
        }
        if (autoGeneratedEmail && regRes.duplicateEmail) {
            cleanEmail = generateSimEmail();
            continue;
        }
        return {false, false, regRes.message, -1, "", ""};
    }

    return {false, false, "Could not generate a unique account number.", -1, "", ""};
}

// Authenticates user with normalized Mobile Number (E.164) and 6-digit PIN
AuthResult AuthService::loginUser(
    const std::string& countryCode,
    const std::string& mobileNumber,
    const std::string& pin
) {
    const PhoneParseResult parsedPhone = PhoneUtils::normalize(countryCode, mobileNumber);
    if (!parsedPhone.valid) {
        return {false, true, parsedPhone.errorMessage, -1, "", ""};
    }

    const std::string& canonicalMobile = parsedPhone.e164;

    // Resolve user record by canonical E.164 mobile number
    const UserAuthRecord userRecord = database.findUserForLogin(canonicalMobile);

    // Striped mutex prevents concurrent login TOCTOU races without holding dbMutex across PBKDF2
    const size_t stripeIdx = std::hash<std::string>{}(canonicalMobile) % LOCK_STRIPES;
    std::lock_guard<std::mutex> identityLock(identityStripes[stripeIdx]);

    const std::int64_t currentTime = static_cast<std::int64_t>(std::time(nullptr));

    // Reconcile any pre-mobile email failure counters into canonical mobile lockout key
    if (userRecord.found && !userRecord.email.empty()) {
        database.reconcileLegacyLoginAttempts(userRecord.email, canonicalMobile);
    }

    const std::int64_t lockedUntil = database.getLoginLockUntil(canonicalMobile);
    if (lockedUntil > currentTime) {
        return {false, false, "Account temporarily locked. Try again later.", -1, "", ""};
    }
    if (lockedUntil > 0 && lockedUntil <= currentTime) {
        database.clearLoginAttempts(canonicalMobile);
    }

    const bool validCredentials = (
        userRecord.found &&
        userRecord.userId > 0 &&
        !userRecord.pinHash.empty() &&
        PinHasher::verifyPin(pin, userRecord.pinHash)
    );

    if (!validCredentials) {
        const std::int64_t newLockTime = currentTime + (LOCKOUT_DURATION_MINUTES * 60);
        const bool locked = database.recordFailedLoginAttempt(
            canonicalMobile,
            MAX_FAILED_ATTEMPTS,
            newLockTime,
            currentTime
        );

        if (locked) {
            return {false, false, "Account temporarily locked for 15 minutes.", -1, "", ""};
        }

        // Generic response prevents mobile-number enumeration
        return {false, false, "Invalid credentials.", -1, "", ""};
    }

    const AccountLoginStatus accStatus = database.findAccountForUser(userRecord.userId);
    if (!accStatus.found) {
        return {false, false, "No ATM account found for this user.", -1, "", ""};
    }

    if (accStatus.status != "active") {
        return {false, false, "Account is not active.", -1, "", ""};
    }

    database.clearLoginAttempts(canonicalMobile);

    return {true, false, "Login successful.", userRecord.userId, accStatus.accountNumber, canonicalMobile};
}

// Safely links a validated E.164 mobile number to an existing unlinked account after PIN verification
AuthResult AuthService::linkMobileToLegacyUser(
    const std::string& accountOrEmail,
    const std::string& pin,
    const std::string& countryCode,
    const std::string& mobileNumber
) {
    const std::string cleanLegacy = normalizeLegacyIdentifier(accountOrEmail);
    if (cleanLegacy.empty()) {
        return {false, true, "Existing 12-digit card number or email is required.", -1, "", ""};
    }

    const PhoneParseResult parsedPhone = PhoneUtils::normalize(countryCode, mobileNumber);
    if (!parsedPhone.valid) {
        return {false, true, parsedPhone.errorMessage, -1, "", ""};
    }

    const UserAuthRecord userRecord = database.findLegacyUserForLinking(cleanLegacy);
    const std::string lockoutKey = (userRecord.found && !userRecord.email.empty())
        ? userRecord.email
        : cleanLegacy;

    const size_t stripeIdx = std::hash<std::string>{}(lockoutKey) % LOCK_STRIPES;
    std::lock_guard<std::mutex> identityLock(identityStripes[stripeIdx]);

    const std::int64_t currentTime = static_cast<std::int64_t>(std::time(nullptr));

    if (userRecord.found && !userRecord.email.empty() && lockoutKey != cleanLegacy) {
        database.reconcileLegacyLoginAttempts(cleanLegacy, lockoutKey);
    }

    const std::int64_t lockedUntil = database.getLoginLockUntil(lockoutKey);
    if (lockedUntil > currentTime) {
        return {false, false, "Account temporarily locked. Try again later.", -1, "", ""};
    }
    if (lockedUntil > 0 && lockedUntil <= currentTime) {
        database.clearLoginAttempts(lockoutKey);
    }

    const bool validCredentials = (
        userRecord.found &&
        userRecord.userId > 0 &&
        !userRecord.pinHash.empty() &&
        PinHasher::verifyPin(pin, userRecord.pinHash)
    );

    if (!validCredentials) {
        const std::int64_t newLockTime = currentTime + (LOCKOUT_DURATION_MINUTES * 60);
        const bool locked = database.recordFailedLoginAttempt(
            lockoutKey,
            MAX_FAILED_ATTEMPTS,
            newLockTime,
            currentTime
        );
        if (locked) {
            return {false, false, "Account temporarily locked for 15 minutes.", -1, "", ""};
        }
        return {false, false, "Invalid credentials.", -1, "", ""};
    }

    const AccountLoginStatus accStatus = database.findAccountForUser(userRecord.userId);
    if (!accStatus.found) {
        return {false, false, "No ATM account found for this user.", -1, "", ""};
    }
    if (accStatus.status != "active") {
        return {false, false, "Account is not active.", -1, "", ""};
    }
    if (!userRecord.mobileNumber.empty()) {
        return {false, true, "This account already has a linked mobile number. Please sign in with Mobile Number & PIN.", -1, "", ""};
    }

    const LinkMobileResult linkRes = database.linkMobileNumberToUser(userRecord.userId, parsedPhone.e164);
    if (!linkRes.success) {
        return {false, true, linkRes.message, -1, "", ""};
    }

    database.clearLoginAttempts(lockoutKey);
    database.clearLoginAttempts(parsedPhone.e164);

    return {true, false, "Mobile number linked successfully.", userRecord.userId, accStatus.accountNumber, parsedPhone.e164};
}
