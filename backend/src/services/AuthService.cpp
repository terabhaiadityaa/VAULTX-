std::string trimCopy(std::string value) {
    size_t start = value.find_first_not_of(" \t\n\r");
    if (start == std::string::npos) return "";
    size_t end = value.find_last_not_of(" \t\n\r");
    return value.substr(start, end - start + 1);
}

std::string normalizeLegacyIdentifier(const std::string& rawIdentifier) {
    std::string clean = trimCopy(rawIdentifier);
    std::transform(clean.begin(), clean.end(), clean.begin(), [](unsigned char ch) {
        return static_cast<char>(std::tolower(ch));
    });
    if (!clean.empty() && std::all_of(clean.begin(), clean.end(), [](unsigned char c) {
            return std::isdigit(c) || c == ' ' || c == '-';
        })) {
        clean.erase(
            std::remove_if(clean.begin(), clean.end(), [](unsigned char c) {
                return c == ' ' || c == '-';
            }),
            clean.end()
        );
    }
    return clean;
}

